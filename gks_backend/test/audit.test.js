const test = require('node:test');
const assert = require('node:assert/strict');

test('administrative writes and audit records commit or roll back together', {skip:process.env.RUN_DB_TESTS!=='true'}, async t => {
    await require('../test-support/database').createTestDatabase(t);
    const {sql,connectDB}=require('../db');await connectDB();
    process.env.ENABLE_SETUP='true';
    const {app}=require('../server');const server=require('http').createServer(app);const io=require('../utils/socket').init(server);
    await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));t.after(()=>new Promise(resolve=>io.close(resolve)));
    const root=`http://127.0.0.1:${server.address().port}/api`;
    let token;
    const call=async(method,path,body,auth=token)=>{
        const response=await fetch(root+path,{method,headers:{'Content-Type':'application/json',...(auth?{Authorization:`Bearer ${auth}`}:{})},body:body===undefined?undefined:JSON.stringify(body)});
        return {status:response.status,data:await response.json()};
    };
    const failAudit=()=>sql.query("CREATE TRIGGER Fixture_Audit_Reject ON SystemLogs INSTEAD OF INSERT AS THROW 51000, 'fixture audit failure', 1;");
    const restoreAudit=()=>sql.query('DROP TRIGGER Fixture_Audit_Reject');
    const password='Fixture-Audit-Password-123';
    await failAudit();
    assert.equal((await call('POST','/ilk-kurulum',{username:'audit-admin',password})).status,500);
    assert.equal((await sql.query('SELECT COUNT(*) AS n FROM Yoneticiler')).recordset[0].n,0);
    await restoreAudit();
    assert.equal((await call('POST','/ilk-kurulum',{username:'audit-admin',password})).status,200);
    token=(await call('POST','/login',{username:'audit-admin',password})).data.token;
    const account={username:'audit-viewer',password,rol:'user'};
    const person={ad_soyad:'Audit Person',rfid:'89000000001',tc:'79000000001',sicil:'99001',ise_giris:'2026-01-01'};
    await failAudit();
    assert.equal((await call('POST','/hesap-ekle',account)).status,500);
    assert.equal((await call('POST','/users',person)).status,500);
    assert.equal((await sql.query('SELECT COUNT(*) AS n FROM Yoneticiler')).recordset[0].n,1);
    assert.equal((await sql.query('SELECT COUNT(*) AS n FROM Users')).recordset[0].n,0);
    await restoreAudit();
    assert.equal((await call('POST','/hesap-ekle',account)).status,200);
    assert.equal((await call('POST','/users',person)).status,200);
    const viewer=(await sql.query("SELECT ID,Token_Version,Sifre_Hash FROM Yoneticiler WHERE Kullanici_Adi='audit-viewer'")).recordset[0];
    const viewerToken=(await call('POST','/login',account)).data.token;
    const uid=(await sql.query('SELECT ID FROM Users')).recordset[0].ID;
    const decision={user_id:uid,tarih:'2026-09-07',onaylanan_dk:0,durum:'Onaylandı',aciklama:'Fixture overtime note'};
    assert.equal((await call('POST','/overtimes/approve',decision)).status,200);
    const beforeDecision=(await sql.query('SELECT * FROM Mesai_Onaylari')).recordset;
    await failAudit();
    assert.equal((await call('DELETE',`/hesap-sil/${viewer.ID}`)).status,500);
    assert.equal((await call('POST','/sifre-degistir',{eskiSifre:password,yeniSifre:'Fixture-New-Password-123'},viewerToken)).status,500);
    assert.equal((await call('POST','/overtimes/approve',{...decision,durum:'Reddedildi'})).status,500);
    assert.equal((await call('POST','/overtimes/approve-bulk',{mesailer:[{...decision,tarih:'2026-09-08'}],durum:'Onaylandı'})).status,500);
    assert.deepEqual((await sql.query('SELECT * FROM Mesai_Onaylari')).recordset,beforeDecision);
    assert.deepEqual((await sql.query("SELECT ID,Token_Version,Sifre_Hash FROM Yoneticiler WHERE Kullanici_Adi='audit-viewer'")).recordset[0],viewer);
    assert.equal((await call('GET','/users',undefined,viewerToken)).status,200);
    await restoreAudit();
    const changed=await Promise.all([1,2].map(()=>call('POST','/sifre-degistir',{eskiSifre:password,yeniSifre:'Fixture-New-Password-123'},viewerToken)));
    assert.deepEqual(changed.map(r=>r.status).sort(),[200,401]);
    assert.equal((await call('GET','/users',undefined,viewerToken)).status,401);
    assert.equal((await call('DELETE',`/hesap-sil/${viewer.ID}`)).status,200);
    assert.equal((await call('POST','/overtimes/approve',{...decision,durum:'Reddedildi'})).status,200);
    const logs=(await sql.query('SELECT * FROM SystemLogs ORDER BY ID')).recordset;
    for(const kind of ['İLK KURULUM','HESAP OLUŞTURMA','YENİ KAYIT','HESAP SİLME','PAROLA DEĞİŞİKLİĞİ','MESAİ KARARI']) assert.ok(logs.some(row=>row.Islem_Tipi===kind),kind);
    assert.equal(logs.filter(row=>row.Islem_Tipi==='PAROLA DEĞİŞİKLİĞİ').length,1);
    const decisions=logs.filter(row=>row.Islem_Tipi==='MESAİ KARARI').map(row=>JSON.parse(row.Detay));
    assert.equal(decisions.length,2);assert.equal(decisions[1].onceki_durum,'Onaylandı');assert.equal(decisions[1].durum,'Reddedildi');
    for(const secret of [password,'Fixture-New-Password-123',viewer.Sifre_Hash,viewerToken]) assert.equal(JSON.stringify(logs).includes(secret),false);
});
