const test = require('node:test');
const assert = require('node:assert/strict');

test('rehiring preserves previous employment and excludes the gap', { skip: process.env.RUN_DB_TESTS !== 'true' }, async t => {
    await require('../test-support/database').createTestDatabase(t);
    const { sql, connectDB } = require('../db');
    await connectDB();
    const { changePersonnel } = require('../services/personnelChanges');
    const { attendance } = require('../services/attendance');
    const { businessToday } = require('../utils/attendance');
    const today=businessToday();
    const day = offset => new Date(Date.parse(today+'T00:00:00Z')+offset*86400000).toISOString().slice(0,10);
    await new sql.Request().input('start',sql.Date,day(-20)).query("INSERT INTO Users(Ad_Soyad,RFID_Kart_No,Sicil_No,Ise_Giris_Tarihi) VALUES('Rehire Fixture','rehire-card','rehire',@start)");
    const uid=(await sql.query('SELECT ID FROM Users')).recordset[0].ID;
    const change=value=>changePersonnel({kind:'status',userId:uid,value,actor:'fixture'});
    await change({durum:0,cikis_tarihi:day(-10),cikis_nedeni:'Fixture exit'});
    assert.equal((await attendance(day(-15),day(-15))).length,1);
    assert.equal((await attendance(day(-5),day(-5))).length,0);
    await require('../test-support/failures').failInsertsOn(sql,'SystemLogs','fixture archive failure');
    await assert.rejects(change({durum:1}));
    assert.equal((await sql.query('SELECT COUNT(*) AS n FROM Personel_Calisma_Gecmisi')).recordset[0].n,0);
    assert.equal((await sql.query('SELECT Durum FROM Users')).recordset[0].Durum,false);
    await require('../test-support/failures').restoreInserts(sql,'SystemLogs');
    await change({durum:1});
    assert.equal((await attendance(day(-15),day(-15))).length,1);
    assert.equal((await attendance(day(-5),day(-5))).length,0);
    assert.equal((await attendance(today,today)).length,1);
    assert.equal((await sql.query('SELECT COUNT(*) AS n FROM Personel_Calisma_Gecmisi')).recordset[0].n,1);
    assert.equal(await change({durum:1}),0);
    await assert.rejects(change({durum:0,cikis_tarihi:day(-1)}),/Çıkış tarihi/);
    await change({durum:0,cikis_tarihi:today,cikis_nedeni:'Same-day reversal'});
    await change({durum:1});
    assert.equal((await sql.query('SELECT COUNT(*) AS n FROM Personel_Calisma_Gecmisi')).recordset[0].n,1);
    assert.equal((await attendance(today,today)).length,1);
    await change({durum:0,cikis_tarihi:today});
    await require('../test-support/failures').failInsertsOn(sql,'SystemLogs','fixture history audit failure');
    await assert.rejects(change({durum:1}));
    assert.equal((await sql.query('SELECT Durum FROM Users')).recordset[0].Durum,false);
    await require('../test-support/failures').restoreInserts(sql,'SystemLogs');
});
